class Command(BaseCommand):
    help = "Load fuel station data from the OPIS fuel prices CSV into the database."

    def add_arguments(self, parser):
        parser.add_argument(
            "--csv",
            type=str,
            default=str(settings.FUEL_CSV_PATH),
            help="Path to the fuel prices CSV file.",
        )
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Clear existing stations before loading.",
        )
        parser.add_argument(
            "--dedupe",
            action="store_true",
            default=True,
            help="Deduplicate stations with same name+city (keep lowest price).",
        )

    def handle(self, *args, **options):
        csv_path = options["csv"]

        if not os.path.exists(csv_path):
            candidates = [
                os.path.join(settings.BASE_DIR, "data", "fuel-prices-for-be-assessment.csv"),
                os.path.join(settings.BASE_DIR, "fuel-prices-for-be-assessment.csv"),
                os.path.join(settings.BASE_DIR, "data", "fuel_prices.csv"),
                os.path.join(os.path.dirname(csv_path), "fuel-prices-for-be-assessment.csv"),
            ]
            for candidate in candidates:
                if os.path.exists(candidate):
                    csv_path = candidate
                    self.stdout.write(f"Using assessment CSV: {csv_path}")
                    break
            else:
                raise CommandError(f"CSV file not found: {csv_path}")

        # Build comprehensive city coordinates lookup
        city_lookup = dict(CITY_COORDS)
        us_cities_path = os.path.join(settings.BASE_DIR, "data", "us_cities.csv")
        if os.path.exists(us_cities_path):
            try:
                with open(us_cities_path, encoding="utf-8", errors="replace") as ucf:
                    for urow in csv.DictReader(ucf):
                        c_name = urow.get("CITY", "").strip().upper()
                        s_code = urow.get("STATE_CODE", "").strip().upper()
                        if c_name and s_code and (c_name, s_code) not in city_lookup:
                            try:
                                city_lookup[(c_name, s_code)] = (
                                    float(urow["LATITUDE"]),
                                    float(urow["LONGITUDE"]),
                                )
                            except (ValueError, KeyError):
                                pass
                self.stdout.write(f"Loaded {len(city_lookup)} cities in geographic coordinate lookup.")
            except Exception as e:
                logger.warning("Failed loading us_cities.csv: %s", e)

        if options["clear"]:
            deleted, _ = FuelStation.objects.all().delete()
            self.stdout.write(f"Cleared {deleted} existing stations.")

        self.stdout.write(f"Loading fuel data from: {csv_path}")

        created = 0
        updated = 0
        skipped = 0
        no_coords = 0
        no_coords_cities = set()

        # Read all rows first, then deduplicate
        all_rows = []

        with open(csv_path, newline="", encoding="utf-8", errors="replace") as f:
            # Check if first line is a title (non-header)
            first_line = f.readline().strip()
            if "," not in first_line or (
                "Date" not in first_line
                and "OPIS" not in first_line
                and "Truckstop" not in first_line
            ):
                # It's a title row, DictReader uses next line as header
                pass
            else:
                # First line is the header
                f.seek(0)

            reader = csv.DictReader(f)

            for row in reader:
                # Handle both CSV formats
                station_id_raw = (
                    row.get("OPIS Station ID", "")
                    or row.get("OPIS Truckstop ID", "")
                ).strip()

                if not station_id_raw:
                    skipped += 1
                    continue

                try:
                    int(station_id_raw)
                except ValueError:
                    skipped += 1
                    continue

                name = (row.get("Truckstop Name", "") or "").strip()
                address = (row.get("Address", "") or "").strip()
                city = (row.get("City", "") or "").strip().upper()
                state = (row.get("State", "") or "").strip().upper()

                try:
                    price = float(row.get("Retail Price", 0) or 0)
                except (ValueError, TypeError):
                    skipped += 1
                    continue

                if price <= 0 or not city or not state:
                    skipped += 1
                    continue

                all_rows.append({
                    "station_id": f"OPIS-{station_id_raw}",
                    "name": name,
                    "address": address,
                    "city": city,
                    "state": state,
                    "price": price,
                })

        self.stdout.write(f"Read {len(all_rows)} valid rows from CSV.")

        # Deduplicate: for same station_id, keep lowest price
        if options.get("dedupe", True):
            seen = {}
            for row in all_rows:
                key = row["station_id"]
                if key not in seen or row["price"] < seen[key]["price"]:
                    seen[key] = row
            all_rows = list(seen.values())
            self.stdout.write(f"After dedup: {len(all_rows)} unique stations.")

        # Bulk insert
        batch = []
        for row in all_rows:
            city = row["city"]
            state = row["state"]

            coords = city_lookup.get((city, state))
            if not coords:
                no_coords += 1
                no_coords_cities.add(f"{city}, {state}")
                continue

            lat, lon = coords
            # Small jitter so stations in same city don't stack
            lat += random.uniform(-0.08, 0.08)
            lon += random.uniform(-0.08, 0.08)

            if not FuelStation.objects.filter(station_id=row["station_id"]).exists():
                batch.append(FuelStation(
                    station_id=row["station_id"],
                    name=row["name"],
                    address=row["address"],
                    city=city,
                    state=state,
                    latitude=round(lat, 6),
                    longitude=round(lon, 6),
                    retail_price=row["price"],
                ))
                created += 1
            else:
                updated += 1

            if len(batch) >= 200:
                FuelStation.objects.bulk_create(batch)
                batch = []

        if batch:
            FuelStation.objects.bulk_create(batch)

        total = FuelStation.objects.count()
        self.stdout.write(
            self.style.SUCCESS(
                f"\nDone! Created: {created}, Already existed: {updated}, "
                f"Skipped: {skipped}, No coordinates: {no_coords}.\n"
                f"Total stations in DB: {total}"
            )
        )
        if no_coords_cities:
            sample = list(no_coords_cities)[:10]
            self.stdout.write(
                f"\nWARN - Cities without coordinates (first 10 of {len(no_coords_cities)}): "
                + ", ".join(sample)
            )
